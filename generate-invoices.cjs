// generate-invoices.cjs — Abstract Emporium invoice system
// Reads orders.jsonl (source of truth) and emits one markdown invoice per order
// into ./invoices/. AE rules: no HST (under $30k threshold), shipping 0 (pickup only).
// Idempotent: re-run regenerates all invoices (safe for a daily cron).
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const ORDERS = path.join(ROOT, 'orders.jsonl');
const OUT = path.join(ROOT, 'invoices');
if (!fs.existsSync(OUT)) fs.mkdirSync(OUT, { recursive: true });

const lines = fs.readFileSync(ORDERS, 'utf8').split('\n').map(l => l.trim()).filter(Boolean);
let n = 0;
for (const line of lines) {
  let o; try { o = JSON.parse(line); } catch (e) { continue; }
  n++;
  const inv = String(n).padStart(4, '0');
  const cust = o.customer || o.customer_name || 'Unknown';
  const items = (o.items || []).map(it => ({
    title: it.title || '(no title)',
    qty: it.qty || 1,
    price: it.price || 0,
    line: (it.qty || 1) * (it.price || 0),
  }));
  const subtotal = o.subtotal != null ? o.subtotal : items.reduce((s, i) => s + i.line, 0);
  const discount = o.discount || 0;
  const tax = o.tax != null ? o.tax : 0;
  const shipping = o.shipping != null ? o.shipping : 0;
  const total = o.total != null ? o.total : (subtotal - discount + tax + shipping);
  const isCredit = total < 0 || items.length === 0;
  const stamps = (o.status === 'paid') ? '1 loyalty stamp (paid order)' : '—';
  const itemRows = items.length
    ? items.map(i => `| ${i.title} | ${i.qty} | $${i.price.toFixed(2)} | $${i.line.toFixed(2)} |`).join('\n')
    : '| (no items) | — | — | — |';

  const md = `# Invoice INV-${inv}

![Abstract Emporium](ae-logo.jpg)

**Abstract Emporium** · abstractemporium.art · abstractemporiumart@outlook.com
Pickup / drop-off only (Thunder Bay, ON) — no shipping.

| Field | Value |
|---|---|
| Invoice # | INV-${inv} |
| Date | ${o.created_at || '—'} |
| Customer | ${cust} |
| Status | ${(o.status || '—').toUpperCase()}${o.flagged ? ' · ⚠ ' + o.flagged : ''} |
| Payment | ${o.payment_method || '—'}${o.paid_at ? ' · ' + o.paid_at : ''} |

## Line Items
| Item | Qty | Unit | Line |
|---|---|---|---|
${itemRows}

## Totals
| | |
|---|---|
| Subtotal | $${subtotal.toFixed(2)} |
| Discount | -$${discount.toFixed(2)} |
| HST/Tax | $${tax.toFixed(2)} *(no HST — under $30k threshold)* |
| Shipping | $${shipping.toFixed(2)} *(pickup only)* |
| **Total** | **$${total.toFixed(2)}** |

**Loyalty:** ${stamps}
**Type:** ${isCredit ? 'CREDIT / REFUND' : 'SALE'}
**Note:** ${o.note || '—'}

---
**Questions / pickup:** abstractemporiumart@outlook.com · abstractemporium.art

*Generated by Hermes · AE invoice system · INV-${inv} mirrors orders.jsonl (source of truth). Edit orders.jsonl, then re-run generate-invoices.cjs.*
`;
  fs.writeFileSync(path.join(OUT, `INV-${inv}.md`), md);
}
console.log(`Generated ${n} invoices -> ${OUT}`);
